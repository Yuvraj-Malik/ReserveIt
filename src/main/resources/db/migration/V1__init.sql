-- ResrvIt schema. Written to run on both PostgreSQL and H2 (PostgreSQL mode).
-- Note: the "groups" table from the plan is called study_groups because GROUPS is a reserved word in H2.

CREATE TABLE departments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(20)  NOT NULL UNIQUE,
    name        VARCHAR(120) NOT NULL
);

CREATE TABLE labs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(30)  NOT NULL UNIQUE,
    name          VARCHAR(120) NOT NULL,
    department_id BIGINT REFERENCES departments(id),
    in_charge_id  BIGINT
);

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(160) NOT NULL UNIQUE,
    password_hash  VARCHAR(100) NOT NULL,
    full_name      VARCHAR(120) NOT NULL,
    role           VARCHAR(30)  NOT NULL,
    status         VARCHAR(30)  NOT NULL,
    department_id  BIGINT REFERENCES departments(id),
    lab_id         BIGINT REFERENCES labs(id),
    roll_no        VARCHAR(40),
    on_leave       BOOLEAN NOT NULL DEFAULT FALSE,
    blocked_until  DATE,
    otp_code       VARCHAR(10),
    otp_expires_at TIMESTAMP,
    created_at     TIMESTAMP NOT NULL,
    deactivated_at TIMESTAMP,
    version        BIGINT NOT NULL DEFAULT 0
);

ALTER TABLE labs ADD CONSTRAINT fk_labs_in_charge FOREIGN KEY (in_charge_id) REFERENCES users(id);

CREATE TABLE rooms (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(30)  NOT NULL UNIQUE,
    name          VARCHAR(120) NOT NULL,
    type          VARCHAR(30)  NOT NULL,
    department_id BIGINT REFERENCES departments(id),
    lab_id        BIGINT REFERENCES labs(id),
    in_charge_id  BIGINT REFERENCES users(id),
    capacity      INT NOT NULL DEFAULT 0,
    bookable      BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE equipment_types (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL UNIQUE,
    description VARCHAR(500)
);

CREATE TABLE equipment (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_tag      VARCHAR(60) NOT NULL UNIQUE,
    type_id        BIGINT NOT NULL REFERENCES equipment_types(id),
    lab_id         BIGINT NOT NULL REFERENCES labs(id),
    status         VARCHAR(30) NOT NULL,
    condition_note VARCHAR(500)
);

CREATE TABLE timetable_slots (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     BIGINT NOT NULL REFERENCES rooms(id),
    day_of_week INT NOT NULL,
    start_time  TIME NOT NULL,
    end_time    TIME NOT NULL,
    course_code VARCHAR(40),
    batch_label VARCHAR(60)
);

CREATE TABLE academic_calendar (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cal_date    DATE NOT NULL UNIQUE,
    day_type    VARCHAR(20) NOT NULL,
    description VARCHAR(200)
);

CREATE TABLE evaluation_schedules (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id        BIGINT NOT NULL REFERENCES users(id),
    lab_id            BIGINT NOT NULL REFERENCES labs(id),
    equipment_type_id BIGINT REFERENCES equipment_types(id),
    course_code       VARCHAR(40) NOT NULL,
    title             VARCHAR(160) NOT NULL,
    eval_date         DATE NOT NULL,
    created_at        TIMESTAMP NOT NULL
);

CREATE TABLE societies (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL UNIQUE,
    description VARCHAR(500),
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP NOT NULL
);

CREATE TABLE society_office_bearers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    society_id BIGINT NOT NULL REFERENCES societies(id),
    user_id    BIGINT NOT NULL REFERENCES users(id),
    position   VARCHAR(80) NOT NULL,
    CONSTRAINT uq_society_bearer UNIQUE (society_id, user_id)
);

CREATE TABLE study_groups (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(120) NOT NULL,
    course_code       VARCHAR(40)  NOT NULL,
    project_title     VARCHAR(200),
    leader_id         BIGINT NOT NULL REFERENCES users(id),
    created_by_id     BIGINT NOT NULL REFERENCES users(id),
    course_faculty_id BIGINT REFERENCES users(id),
    status            VARCHAR(30) NOT NULL,
    created_at        TIMESTAMP NOT NULL
);

CREATE TABLE group_members (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id  BIGINT NOT NULL REFERENCES study_groups(id),
    user_id   BIGINT NOT NULL REFERENCES users(id),
    confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_group_member UNIQUE (group_id, user_id)
);

CREATE TABLE bookings (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind                  VARCHAR(20) NOT NULL,
    status                VARCHAR(20) NOT NULL,
    requester_id          BIGINT NOT NULL REFERENCES users(id),
    group_id              BIGINT REFERENCES study_groups(id),
    society_id            BIGINT REFERENCES societies(id),
    room_id               BIGINT REFERENCES rooms(id),
    lab_id                BIGINT REFERENCES labs(id),
    equipment_type_id     BIGINT REFERENCES equipment_types(id),
    equipment_id          BIGINT REFERENCES equipment(id),
    slot_date             DATE NOT NULL,
    end_date              DATE,
    start_time            TIME,
    end_time              TIME,
    reason                VARCHAR(30),
    reason_text           VARCHAR(500),
    evaluation_id         BIGINT REFERENCES evaluation_schedules(id),
    protected_eval        BOOLEAN NOT NULL DEFAULT FALSE,
    urgent                BOOLEAN NOT NULL DEFAULT FALSE,
    critical              BOOLEAN NOT NULL DEFAULT FALSE,
    critical_note         VARCHAR(500),
    direct_booking        BOOLEAN NOT NULL DEFAULT FALSE,
    emergency             BOOLEAN NOT NULL DEFAULT FALSE,
    queue_rank            BIGINT NOT NULL,
    waitlist_priority     BOOLEAN NOT NULL DEFAULT FALSE,
    claimed_by_id         BIGINT REFERENCES users(id),
    claimed_at            TIMESTAMP,
    decided_by_id         BIGINT REFERENCES users(id),
    decided_at            TIMESTAMP,
    decision_note         VARCHAR(500),
    qr_token              VARCHAR(64) UNIQUE,
    previous_booking_id   BIGINT REFERENCES bookings(id),
    renewal_reminder_sent BOOLEAN NOT NULL DEFAULT FALSE,
    excluded_dates        VARCHAR(2000),
    created_at            TIMESTAMP NOT NULL,
    updated_at            TIMESTAMP NOT NULL,
    version               BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_bookings_slot ON bookings (slot_date, status);
CREATE INDEX idx_bookings_requester ON bookings (requester_id);

CREATE TABLE approvals (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id),
    actor_id   BIGINT REFERENCES users(id),
    action     VARCHAR(30) NOT NULL,
    note       VARCHAR(500),
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE queue_audit (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id),
    actor_id   BIGINT NOT NULL REFERENCES users(id),
    old_rank   BIGINT NOT NULL,
    new_rank   BIGINT NOT NULL,
    reason     VARCHAR(500) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE slot_offers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id    BIGINT NOT NULL REFERENCES bookings(id),
    offered_date  DATE NOT NULL,
    option_rank   INT NOT NULL,
    status        VARCHAR(20) NOT NULL,
    expires_at    TIMESTAMP NOT NULL,
    created_at    TIMESTAMP NOT NULL
);

CREATE TABLE checkouts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id     BIGINT NOT NULL REFERENCES bookings(id),
    equipment_id   BIGINT NOT NULL REFERENCES equipment(id),
    issued_by_id   BIGINT NOT NULL REFERENCES users(id),
    issued_at      TIMESTAMP NOT NULL,
    condition_out  VARCHAR(500),
    due_at         TIMESTAMP NOT NULL,
    returned_at    TIMESTAMP,
    received_by_id BIGINT REFERENCES users(id),
    condition_in   VARCHAR(500),
    late           BOOLEAN NOT NULL DEFAULT FALSE,
    damaged        BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE incidents (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id     BIGINT REFERENCES bookings(id),
    equipment_id   BIGINT REFERENCES equipment(id),
    lab_id         BIGINT NOT NULL REFERENCES labs(id),
    reported_by_id BIGINT NOT NULL REFERENCES users(id),
    description    VARCHAR(1000) NOT NULL,
    status         VARCHAR(20) NOT NULL,
    created_at     TIMESTAMP NOT NULL,
    resolved_at    TIMESTAMP,
    resolved_by_id BIGINT REFERENCES users(id),
    resolution     VARCHAR(1000)
);

CREATE TABLE strikes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id),
    booking_id   BIGINT REFERENCES bookings(id),
    reason       VARCHAR(300) NOT NULL,
    created_at   TIMESTAMP NOT NULL,
    waived       BOOLEAN NOT NULL DEFAULT FALSE,
    waived_by_id BIGINT REFERENCES users(id),
    consumed     BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE maintenance_logs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id  BIGINT REFERENCES equipment(id),
    room_id       BIGINT REFERENCES rooms(id),
    start_date    DATE NOT NULL,
    end_date      DATE NOT NULL,
    reason        VARCHAR(500) NOT NULL,
    created_by_id BIGINT NOT NULL REFERENCES users(id),
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP NOT NULL,
    closed_at     TIMESTAMP
);

CREATE TABLE conversations (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id        BIGINT NOT NULL REFERENCES users(id),
    lab_id            BIGINT NOT NULL REFERENCES labs(id),
    booking_id        BIGINT REFERENCES bookings(id),
    subject           VARCHAR(160) NOT NULL,
    urgent            BOOLEAN NOT NULL DEFAULT FALSE,
    urgent_reason     VARCHAR(300),
    urgent_at         TIMESTAMP,
    status            VARCHAR(20) NOT NULL,
    rating            INT,
    created_at        TIMESTAMP NOT NULL,
    last_message_at   TIMESTAMP NOT NULL,
    first_response_at TIMESTAMP
);

CREATE TABLE messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id),
    sender_id       BIGINT NOT NULL REFERENCES users(id),
    ciphertext      VARCHAR(8000) NOT NULL,
    iv              VARCHAR(40) NOT NULL,
    created_at      TIMESTAMP NOT NULL
);

CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id),
    message    VARCHAR(500) NOT NULL,
    link       VARCHAR(200),
    is_read    BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_notifications_user ON notifications (user_id, is_read);

CREATE TABLE settings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key   VARCHAR(80) NOT NULL UNIQUE,
    setting_value VARCHAR(500) NOT NULL
);

