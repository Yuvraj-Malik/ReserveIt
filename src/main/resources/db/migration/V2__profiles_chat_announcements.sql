-- Chat: booking threads (student <-> staff) and direct staff chats
ALTER TABLE conversations ALTER COLUMN student_id DROP NOT NULL;
ALTER TABLE conversations ALTER COLUMN lab_id DROP NOT NULL;
ALTER TABLE conversations ADD COLUMN kind VARCHAR(20) DEFAULT 'BOOKING' NOT NULL;

CREATE TABLE conversation_members (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id),
    user_id         BIGINT NOT NULL REFERENCES users(id),
    last_read_at    TIMESTAMP,
    CONSTRAINT uq_conversation_member UNIQUE (conversation_id, user_id)
);

-- Announcements sent by admins (each also becomes a notification per recipient)
CREATE TABLE announcements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id       BIGINT NOT NULL REFERENCES users(id),
    audience        VARCHAR(200) NOT NULL,
    message         VARCHAR(1000) NOT NULL,
    recipient_count INT NOT NULL,
    created_at      TIMESTAMP NOT NULL
);
